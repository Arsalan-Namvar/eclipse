"""Opaque Strata base paint for compositor-controlled application materials.

Strata's documented style.css provider is watched live. One owned block is
updated in the user's stylesheet; personal rules remain intact and win.
"""
import os
from pathlib import Path
import re
import tempfile

BEGIN = '/* Eclipse material begin */'
END = '/* Eclipse material end */'


def atomic_write(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, pending = tempfile.mkstemp(prefix='.eclipse-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(text)
        os.replace(pending, path)
    finally:
        if os.path.exists(pending):
            os.unlink(pending)


def opaque_background(config):
    """Avoid stacking native surface alpha with Hyprland's whole-window fade."""
    root = Path(config) / 'strata'
    css = '''/* Generated by Eclipse; edit style.css for personal overrides. */
window { background: @strata_bg; }
window box, window overlay, window stack, window grid,
window paned, window scrolledwindow, window viewport,
window gridview, window listview, window columnview, window flowbox,
window .content, window .view, window .icons-pane, window .columns,
window .file-list, window .mode-list, window .file-icons,
window .sidebar-shell, window .sidebar-scroll {
  background-color: transparent; background-image: none;
}
window headerbar, window .tab-strip, window .mode-pane-header,
window .column-header, window .preview-header {
  background: @strata_surface;
}
window popover, window popover contents { background: @strata_surface; }
'''
    user = root / 'style.css'
    original = user.read_text() if user.exists() else ''
    # Strata loads CSS from a string, so relative imports have no base URI.
    # Keep one owned block in the watched stylesheet; personal rules follow.
    original = re.sub(r'/\* Eclipse material begin \*/.*?/\* Eclipse material end \*/\n?',
                      '', original, flags=re.S)
    original = original.replace('@import url("eclipse-material.css"); /* Eclipse material */\n', '')
    original = original.replace('window * { background-color: transparent; background-image: none; }\n', '')
    atomic_write(user, BEGIN + '\n' + css + END + '\n' + original)


